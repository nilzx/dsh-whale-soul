import { readFileSync, writeFileSync } from 'node:fs'

const sources = ['locale-text.js', 'locale-client.js'].map((name) => readFileSync(new URL(name, import.meta.url), 'utf8'))
const exports = sources.flatMap((source) => [...source.matchAll(/^export (?:const|function) ([A-Za-z0-9_]+)/gm)].map((match) => match[1]))
const body = sources.map((source) => source.replace(/^import .*\n/gm, '').replace(/^export /gm, '')).join('\n')
const output = `// Generated by src/build-client.js; edit locale-text.js and locale-client.js.\nwindow.__ModuleLoader__.load({\n  id: 'dsh-whale-soul',\n  factory() {\n${body.split('\n').map((line) => line ? `    ${line}` : '').join('\n')}\n    return { ${exports.join(', ')} };\n  },\n});\n`
writeFileSync(new URL('client.js', import.meta.url), output)
